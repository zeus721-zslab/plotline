import type { EventId } from './lineData.ts';
import type { Claim } from './storyChecks.ts';

export type Beat = {
	// 장-비트(예: 5-4)
	id: string;
	text: string;
	// 이 비트의 스크롤 길이(vh)
	heightVh: number;
	claims: Claim[];
};

export type Chapter = {
	number: number;
	title: string;
	beats: Beat[];
};

// 시제품 layout(flow.src.html :171): 높이 = clamp(80 + 0.9 × 글자 수, 170, 330)vh
const BEAT_VH_BASE = 80;
const BEAT_VH_PER_CHAR = 0.9;
const BEAT_VH_MIN = 170;
const BEAT_VH_MAX = 330;
// 점수(판)는 ×10 정수 행으로 저장한다(75판 = 750). 시간은 ns 행이라 ÷10 이 "1억분의 N초"의 N 이다
const SCORE_SCALE = 10;
const NANOSECONDS_PER_UNIT = 10;
const SUMMER_MONTHS = [6, 7, 8];
const WINTER_MONTHS = [12, 1, 2];

export function beatHeightVh(text: string): number {
	const height = BEAT_VH_BASE + Array.from(text).length * BEAT_VH_PER_CHAR;
	return Math.max(BEAT_VH_MIN, Math.min(BEAT_VH_MAX, height));
}

function beat(id: string, text: string, claims: Claim[] = []): Beat {
	return { id, text, heightVh: beatHeightVh(text), claims };
}

function date(event: EventId, year: number): Claim {
	return { kind: 'date', event, year };
}

function value(event: EventId, amount: number): Claim {
	return { kind: 'value', event, min: amount, max: amount };
}

function scaled(event: EventId, divisor: number, amount: number): Claim {
	return { kind: 'scaled-value', event, divisor, min: amount, max: amount };
}

function rounded(event: EventId, divisor: number, expected: number): Claim {
	return { kind: 'rounded-value', event, divisor, expected };
}

function yearsAfter(from: EventId, to: EventId, min: number, max: number = min): Claim {
	return { kind: 'years-after', from, to, min, max };
}

function monthIn(event: EventId, year: number, months: number[]): Claim {
	return { kind: 'month-in', event, year, months };
}

