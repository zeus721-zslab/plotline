const BADGE_FREE_LAST_SENTENCE_BEAT = '7-5';

/** 비트 beatId 의 sentenceIndex 번째 문장(전체 sentenceCount 개)에 붙일 배지. 없으면 null */
export function badgeOf(
	beatId: string,
	sentenceIndex: number,
	sentenceCount: number
): string | null {
	const badge = BADGES.get(beatId);
	if (badge === undefined) return null;
	const badgeFree = beatId === BADGE_FREE_LAST_SENTENCE_BEAT && sentenceIndex === sentenceCount - 1;
	return badgeFree ? null : badge;
}

